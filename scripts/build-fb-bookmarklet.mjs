// Builds the Facebook browser helper (scripts/fb-bookmarklet.src.ts) into one self-contained line of
// plain JavaScript and writes it to lib/fb-bookmarklet.ts. It runs inside facebook.com, so it may not
// depend on any bundler helper. Run: node scripts/build-fb-bookmarklet.mjs
import ts from "typescript";
import fs from "fs";

const src = fs.readFileSync("scripts/fb-bookmarklet.src.ts", "utf8");
const { outputText } = ts.transpileModule(src, {
  compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.None, removeComments: true },
});
const code = outputText
  .split("\n")
  .map((l) => l.trim())
  .filter(Boolean)
  .join(" ");
fs.writeFileSync(
  "lib/fb-bookmarklet.ts",
  `// Generated by scripts/build-fb-bookmarklet.mjs from scripts/fb-bookmarklet.src.ts: do not edit by hand.\n` +
    `/** javascript: link for the bookmarks bar (set on the anchor after render: React blocks javascript: hrefs) */\n` +
    `export const FB_BOOKMARKLET = ${JSON.stringify("javascript:" + encodeURIComponent(code + ";void 0"))};\n`
);
console.log("bookmarklet chars", code.length);
