export function isFaqList(v: unknown): v is FaqItem[] {
  return (
    Array.isArray(v) &&
    v.length <= 200 &&
    v.every(
      (x) =>
        x &&
        typeof x === "object" &&
        typeof (x as FaqItem).q === "string" &&
        typeof (x as FaqItem).a === "string" &&
        typeof (x as FaqItem).topic === "string" &&
        (x as FaqItem).q.length <= 300 &&
        (x as FaqItem).a.length <= 2000 &&
        (x as FaqItem).topic.length <= 60
    )
  );
}
